-- Packages whose number of visits is chosen by the patient at sale (laser: one package per device).
-- Owner decision 2026-11-14: "الزيارات خليها عدد زيارات تحددها المريضة".
-- Model: a pricing package flagged booking_variable_visits is a ONE-visit pattern (booking_visits = 1, one service line).
-- Its template price is the price of ONE visit. At sale the receptionist sends visit_terms {visits, days?}; the contract price is
-- price-per-visit x visits (no free price), the single line is repeated for every visit, and the value is split per visit.
-- Additive: two new columns, two trigger functions, one check constraint, and a guarded text patch of clinic_reception.service_operation
-- (same technique as 20261114170000). Orthodontic terms are untouched and cannot be combined with visit_terms.
-- Rollback: supabase/rollbacks/20261114190000_reception_variable_visits.rollback.sql
begin;

do $guard$ begin
  if to_regclass('public.pricing_packages') is null
     or not exists (select 1 from information_schema.columns where table_schema='clinic_reception' and table_name='package_templates' and column_name='pricing_package_id') then
    raise exception 'catalog readiness migration (pricing packages -> templates) is required first';
  end if;
end $guard$;

alter table public.pricing_packages
  add column booking_variable_visits boolean not null default false;
alter table public.pricing_packages
  add constraint pricing_packages_variable_visits_chk
  check (not booking_variable_visits or booking_visits is null or booking_visits = 1);

alter table clinic_reception.package_templates
  add column variable_visits boolean not null default false;

-- Templates are generated by sync_catalog from pricing_packages: copy the flag without touching that function.
create function clinic_reception.package_template_variable_flag()
returns trigger language plpgsql security definer set search_path = pg_catalog, public as $$
begin
  if new.pricing_package_id is not null then
    new.variable_visits := coalesce((select p.booking_variable_visits from public.pricing_packages p where p.id = new.pricing_package_id), false);
  end if;
  return new;
end $$;
revoke all on function clinic_reception.package_template_variable_flag() from public, anon, authenticated;
create trigger trg_package_template_variable_flag
  before insert on clinic_reception.package_templates
  for each row execute function clinic_reception.package_template_variable_flag();

-- Toggling the flag on an existing pricing package updates its active template (the sync fingerprint does not include it).
create function public.pricing_package_variable_sync()
returns trigger language plpgsql security definer set search_path = pg_catalog, public as $$
begin
  if new.booking_variable_visits is distinct from old.booking_variable_visits then
    update clinic_reception.package_templates set variable_visits = new.booking_variable_visits
     where pricing_package_id = new.id and active;
  end if;
  return new;
end $$;
revoke all on function public.pricing_package_variable_sync() from public, anon, authenticated;
create trigger trg_pricing_package_variable_sync
  after update of booking_variable_visits on public.pricing_packages
  for each row execute function public.pricing_package_variable_sync();

